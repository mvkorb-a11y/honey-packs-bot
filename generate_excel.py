def create_recipe_sheet(sheet_title, main_title, recipes_data):
    ws = wb.create_sheet(title=sheet_title)
    ws.views.sheetView[0].showGridLines = True
    ws.append([])
    ws.append([main_title])
    ws.cell(row=2, column=1).font = FONT_TITLE
    ws.row_dimensions[2].height = 25

    headers = ["Рецепт / Название", "Категория / Тип", "Ингредиент", "Вес (г / порция)", "Ориентировочная мера", "Роль ингредиента", "Технология приготовления / Хранение"]
    ws.append(headers)
    ws.row_dimensions[3].height = 28

    for col_idx, text in enumerate(headers, 1):
        cell = ws.cell(row=3, column=col_idx)
        cell.font = FONT_HEADER
        cell.fill = HEADER_FILL
        cell.alignment = ALIGN_CENTER
        cell.border = THIN_BORDER

    current_row = 4
    for name, priority, ingredients, tech in recipes_data:
        start_row = current_row
        
        for idx, (ing_name, weight, measure, role) in enumerate(ingredients):
            if idx == 0:
                row_values = [name, priority, ing_name, weight, measure, role, tech]
            else:
                row_values = ["", "", ing_name, weight, measure, role, ""]
                
            ws.append(row_values)
            ws.row_dimensions[current_row].height = 20
            
            for col_idx in range(1, 8):
                cell = ws.cell(row=current_row, column=col_idx)
                cell.font = FONT_NORMAL
                cell.border = THIN_BORDER
                if col_idx in [4, 5]:
                    cell.alignment = ALIGN_CENTER
                elif col_idx in [1, 2]:
                    cell.alignment = ALIGN_CENTER
                    if "ТОП" in priority or "База" in priority or "Запеченный" in priority or "No-Bake" in priority:
                        cell.fill = ACCENT_FILL
                else:
                    cell.alignment = ALIGN_LEFT
                    
            current_row += 1
            
        end_row = current_row - 1
        
        ws.merge_cells(start_row=start_row, start_column=1, end_row=end_row, end_column=1)
        ws.merge_cells(start_row=start_row, start_column=2, end_row=end_row, end_column=2)
        ws.merge_cells(start_row=start_row, start_column=7, end_row=end_row, end_column=7)
        
        cell_name = ws.cell(row=start_row, column=1)
        cell_name.font = FONT_BOLD
        cell_name.alignment = ALIGN_CENTER
        if "ТОП" in priority or "База" in priority or "Запеченный" in priority or "No-Bake" in priority:
            cell_name.fill = ACCENT_FILL
            
        cell_prio = ws.cell(row=start_row, column=2)
        cell_prio.font = FONT_BOLD
        cell_prio.alignment = ALIGN_CENTER
        if "ТОП" in priority or "База" in priority or "Запеченный" in priority or "No-Bake" in priority:
            cell_prio.fill = ACCENT_FILL
            
        cell_tech = ws.cell(row=start_row, column=7)
        cell_tech.alignment = ALIGN_LEFT

    column_widths = [25, 16, 35, 18, 25, 45, 52]
    for i, width in enumerate(column_widths, 1):
        ws.column_dimensions[get_column_letter(i)].width = width

